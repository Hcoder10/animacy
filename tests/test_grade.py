def test_extract_json_is_robust_to_prose_fences_and_junk():
    good = {"clips": [{"clip": 1, "scores": {"overall": 7}}], "notes": "n"}
    text = "Sure! Here is my review:\n```json\n" + json.dumps(good) + "\n```\nHope this helps { not json"
    assert kimi.extract_json(text) == good
    text2 = "{ broken { " + json.dumps(good)
    assert kimi.extract_json(text2) == good
    with pytest.raises(kimi.KimiError):
        kimi.extract_json("no json here at all")


def test_parse_stream_json_collects_assistant_text():
    lines = [json.dumps({"role": "assistant", "content": "part one "}), "garbage line",
             json.dumps({"role": "meta", "content": "ignored"}), json.dumps({"role": "assistant", "content": '{"a": 1}'})]
    assert kimi.extract_json(kimi.parse_stream_json("\n".join(lines))) == {"a": 1}


def test_validate_response_catches_missing_duplicate_and_out_of_range():
    ok = {"clips": [{"clip": n, "description": "moves", "scores": {k: 7 for k in rubric.SCORE_KEYS}} for n in (1, 2, 3)]}
    assert rubric.validate_response(ok, [1, 2, 3]) == []
    missing = {"clips": ok["clips"][:2]}
    assert any("missing" in e for e in rubric.validate_response(missing, [1, 2, 3]))
    dup = {"clips": ok["clips"] + [ok["clips"][0]]}
    assert any("twice" in e for e in rubric.validate_response(dup, [1, 2, 3]))
    bad = json.loads(json.dumps(ok))
    bad["clips"][1]["scores"]["overall"] = 11
    assert any("out of range" in e for e in rubric.validate_response(bad, [1, 2, 3]))
    nodesc = json.loads(json.dumps(ok))
    nodesc["clips"][0]["description"] = ""
    assert any("no description" in e for e in rubric.validate_response(nodesc, [1, 2, 3]))
    assert rubric.validate_response({"nope": 1}, [1]) == ["no 'clips' list"]


# ---------------------------------------------------------------- the gate
def _records(robot, model_scores, vendor_scores=(8, 8, 8, 8, 8), retrieval=None):
    recs = []
    for mv, seeds in zip(MOVEMENT_KEYS, model_scores):
        for k, v in enumerate(seeds):
            recs.append({"robot": robot, "movement": mv, "source": "model", "seed": k, "overall": v, "scores": {"overall": v}})
    for mv, v in zip(MOVEMENT_KEYS, vendor_scores):
        recs.append({"robot": robot, "movement": mv, "source": VENDOR, "seed": None, "overall": v, "scores": {"overall": v}})
    for mv, seeds in (retrieval or {}).items():
        for k, v in enumerate(seeds):
            recs.append({"robot": robot, "movement": mv, "source": "retrieval", "seed": k, "overall": v, "scores": {"overall": v}})
    return recs


def test_gate_passes_only_when_every_movement_mean_reaches_the_threshold():
    assert GATE_THRESHOLD == 8.0
    g = gate(_records("lamp", [(8, 8), (9, 8), (8, 9), (10, 8), (8, 8)]), "lamp")
    assert g["pass"] is True
    assert all(g["per_movement"][mv]["pass"] for mv in MOVEMENT_KEYS)
    # exactly on the line passes; one tenth below fails
    assert gate(_records("lamp", [(8, 8)] * 5), "lamp")["pass"] is True
    assert gate(_records("lamp", [(8, 8)] * 4 + [(7, 8)]), "lamp")["pass"] is False


def test_gate_uses_mean_over_seeds_not_best_of_seeds():
    g = gate(_records("lamp", [(10, 6), (9, 9), (8, 8), (8, 9), (8, 8)]), "lamp")
    assert g["per_movement"]["greeting"]["mean"] == 8.0 and g["per_movement"]["greeting"]["pass"] is True
    g2 = gate(_records("lamp", [(9, 6), (9, 9), (8, 8), (8, 9), (8, 8)]), "lamp")
    assert g2["per_movement"]["greeting"]["mean"] == 7.5
    assert g2["pass"] is False
    assert g2["best_of_seeds_would_pass"] is True, "best-of-seeds is reported but must not decide"


def test_gate_fails_when_a_movement_is_missing_or_unscored():
    recs = _records("lamp", [(9, 9), (9, 9), (9, 9), (9, 9), (9, 9)])
    recs = [r for r in recs if not (r["source"] == "model" and r["movement"] == "thinking")]
    g = gate(recs, "lamp")
    assert g["pass"] is False and g["per_movement"]["thinking"]["n"] == 0
    recs2 = _records("lamp", [(9, 9), (9, 9), (9, 9), (9, 9), (9, None)])
    g2 = gate(recs2, "lamp")
    assert g2["per_movement"]["thinking"]["n"] == 1 and g2["pass"] is True


