# ---------------------------------------------------------------- reels
def _fake_clip(robot, mv, source, seed, seconds=3.0):
    n = int(seconds * 30) + 1
    prof = find_robot(robot)
    table = pd.DataFrame({"t": np.arange(n) / 30.0, **{j.name: np.full(n, j.rest) for j in prof.joints}})
    return ClipSpec(id=f"{robot}/{mv}/{source}/s{seed}", robot=robot, movement=mv, source=source, seed=seed,
                    card_line="x", table=table, audio=np.zeros(int(seconds * 16000), np.float32))


def _fake_clips(robot="lamp", seeds=2, sources=("model", "retrieval", "envelope")):
    out = []
    for mv in MOVEMENT_KEYS:
        for s in sources:
            for k in range(seeds):
                out.append(_fake_clip(robot, mv, s, k))
        out.append(_fake_clip(robot, mv, VENDOR, None, seconds=4.0))
    return out


def test_reel_order_is_seeded_and_numbers_are_a_permutation():
    clips = _fake_clips()
    a = number_and_shuffle(clips, 0)
    b = number_and_shuffle(clips, 0)
    c = number_and_shuffle(clips, 1)
    assert [e.clip.id for e in a] == [e.clip.id for e in b]
    assert [e.clip.id for e in a] != [e.clip.id for e in c]
    assert [e.number for e in a] == list(range(1, len(clips) + 1))
    assert [e.clip.id for e in a] != [c_.id for c_ in clips], "shuffle must change the order"
    assert sorted(e.clip.id for e in a) == sorted(c_.id for c_ in clips)


def test_reels_are_consecutive_and_under_the_limit():
    numbered = number_and_shuffle(_fake_clips(), 3)
    reels = chunk_reels(numbered, "lamp", max_seconds=60)
    assert len(reels) >= 2
    seen = []
    for r in reels:
        assert r.numbers == list(range(r.numbers[0], r.numbers[-1] + 1))
        assert r.seconds <= 60 * 1.05
        seen.extend(r.numbers)
    assert seen == list(range(1, len(numbered) + 1))


