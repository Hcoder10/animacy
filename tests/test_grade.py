def test_resample_and_urdf_frames_match_table_length():
    prof = find_robot("lamp")
    t = np.array([0.0, 0.05, 0.10, 0.15, 0.20])           # a 20 Hz vendor table
    table = pd.DataFrame({"t": t, **{j.name: j.rest + np.linspace(0, 10, 5) for j in prof.joints}})
    r = resample_table(table, 30)
    assert len(r) == 7 and abs(r["t"].iloc[-1] - 0.2) < 1e-9
    frames = urdf_frames(r, prof)
    assert len(frames) == 7 and set(frames[0]) == {j.urdf_joint for j in prof.joints}
    assert abs(frames[-1]["base_yaw"] - np.deg2rad(prof.joint("base_yaw").rest + 10)) < 1e-6


def test_most_active_window_picks_the_gesture_not_the_hold():
    from animacy.grade.movements import most_active_window

    t = np.arange(0, 12.0, 0.05)
    x = np.zeros_like(t)
    x[(t >= 5) & (t < 8)] = 30 * np.sin(2 * np.pi * 2 * t[(t >= 5) & (t < 8)])   # the gesture sits at 5..8 s
    table = pd.DataFrame({"t": t, "a": x, "b": np.zeros_like(t)})
    w = most_active_window(table, 6.0)
    assert abs(w["t"].iloc[0]) < 1e-9 and abs(w["t"].iloc[-1] - 6.0) < 0.06
    assert w["a"].abs().max() > 25, "the window must contain the gesture"
    short = most_active_window(table[table["t"] < 3.0], 6.0)
    assert len(short) == int(3.0 / 0.05)


